-- 1. OYUNCU PROFİLLERİ VE XP / LEVEL TABLOSU (profiles)
CREATE TABLE IF NOT EXISTS public.profiles (
  id TEXT PRIMARY KEY,
  username TEXT NOT NULL,
  auth_provider TEXT DEFAULT 'guest',
  email TEXT,
  avatar TEXT DEFAULT '😎',
  xp INTEGER DEFAULT 0,
  level INTEGER DEFAULT 1,
  games_played INTEGER DEFAULT 0,
  questions_correct INTEGER DEFAULT 0,
  friends JSONB DEFAULT '[]'::jsonb,
  bonds JSONB DEFAULT '{}'::jsonb,
  updated_at TIMESTAMPTZ DEFAULT NOW(),
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. CANLI OYUN ODALARI, KLASİK THE TEST DÜELLOLARI VE TAKIM ODALARI (senceo_rooms)
CREATE TABLE IF NOT EXISTS public.senceo_rooms (
  code TEXT PRIMARY KEY,
  room_type TEXT DEFAULT 'classic', -- 'classic' (The Test) veya 'live_arena' (1v1, 2v2, 3v3, 4v4, 5v5, ffa)
  arena_format TEXT DEFAULT '1v1',
  status TEXT DEFAULT 'waiting_p2',
  current_round INTEGER DEFAULT 1,
  whose_turn TEXT DEFAULT 'p1',
  category TEXT DEFAULT 'genel',
  theme TEXT DEFAULT 'cosmic',
  p1_name TEXT,
  p2_name TEXT,
  question_ids JSONB DEFAULT '[]'::jsonb,
  used_question_ids JSONB DEFAULT '[]'::jsonb,
  p1_answers JSONB DEFAULT '[]'::jsonb,
  p2_guesses JSONB DEFAULT '[]'::jsonb,
  p1_comments JSONB DEFAULT '[]'::jsonb,
  p2_comments JSONB DEFAULT '[]'::jsonb,
  payload JSONB DEFAULT '{}'::jsonb,
  updated_at TIMESTAMPTZ DEFAULT NOW(),
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. TAMAMLANAN OYUNLAR VE İKİLİ BAĞ (BOND LEVEL) GEÇMİŞİ (match_history)
CREATE TABLE IF NOT EXISTS public.match_history (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  room_code TEXT NOT NULL,
  round_number INTEGER DEFAULT 1,
  p1_name TEXT NOT NULL,
  p2_name TEXT NOT NULL,
  match_percentage INTEGER NOT NULL,
  correct_count INTEGER DEFAULT 0,
  total_questions INTEGER DEFAULT 5,
  summary JSONB DEFAULT '{}'::jsonb,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- ============================================================================
-- ÇOK ÖNEMLİ: TEK PUBLIC / ANON API KEY İLE OKUMA / YAZMA / GÜNCELLEME
-- YAPILABİLMESİ İÇİN ROW LEVEL SECURITY (RLS) POLİTİKALARI
-- ============================================================================

ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.senceo_rooms ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.match_history ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Public Full Access on profiles" ON public.profiles;
CREATE POLICY "Public Full Access on profiles"
  ON public.profiles
  FOR ALL
  TO public, anon, authenticated
  USING (true)
  WITH CHECK (true);

DROP POLICY IF EXISTS "Public Full Access on senceo_rooms" ON public.senceo_rooms;
CREATE POLICY "Public Full Access on senceo_rooms"
  ON public.senceo_rooms
  FOR ALL
  TO public, anon, authenticated
  USING (true)
  WITH CHECK (true);

DROP POLICY IF EXISTS "Public Full Access on match_history" ON public.match_history;
CREATE POLICY "Public Full Access on match_history"
  ON public.match_history
  FOR ALL
  TO public, anon, authenticated
  USING (true)
  WITH CHECK (true);

-- Anon ve Authenticated rollere tam tablo yetkisi ver
GRANT ALL ON TABLE public.profiles TO anon, authenticated, service_role;
GRANT ALL ON TABLE public.senceo_rooms TO anon, authenticated, service_role;
GRANT ALL ON TABLE public.match_history TO anon, authenticated, service_role;
